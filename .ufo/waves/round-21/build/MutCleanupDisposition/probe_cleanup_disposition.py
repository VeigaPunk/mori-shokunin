#!/usr/bin/env python3
"""Proposed round21 input-mutation probe; run only during L1 verification.

One synthetic required wave: unresolved -> disposed + same-actor receipt.
The same copied auditor runs four times, with no census, pin, or selftest.
All generated bytes and Git writes stay beneath this script's assigned seat.
Exit 0 = killed; 1 = survived; 2 = inconclusive/setup failure.
"""

import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


LANE = Path("/home/vgpnk/Projects/shokunin/mori-shokunin")
SEAT = LANE / ".ufo/waves/round-21/build/MutCleanupDisposition"
WAVE = "aggregator-r10"
CLEANUP_ACTOR = "synthetic-cleanup-author"
INDEPENDENT_ACTOR = "synthetic-independent-reviewer"
FINDING = (
    f"mori-evidence-loss:audit:{WAVE}:independent_disposition:"
    "independent_actor_not_distinct"
)
TIMEOUT_SECONDS = 10


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def json_bytes(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")


def check(record, counts, pin_allowed, returncode, finding=None):
    errors = []
    if record["returncode"] != returncode:
        errors.append(f"returncode: expected {returncode}, got {record['returncode']}")
    data = record["json"]
    if not isinstance(data, dict):
        return errors + ["stdout is not one JSON object"]
    if data.get("schema") != "mori-evidence-loss-audit-v1":
        errors.append("wrong audit schema")
    if data.get("pin_allowed") is not pin_allowed:
        errors.append(f"pin_allowed must be {pin_allowed}")
    for key, expected in counts.items():
        if type(data.get(key)) is not int or data[key] != expected:
            errors.append(f"{key}: expected {expected}, got {data.get(key)!r}")
    issues = data.get("issues")
    if not isinstance(issues, list):
        errors.append("issues is not a list")
    elif finding is not None and not any(
        isinstance(issue, dict) and issue.get("finding_id") == finding
        for issue in issues
    ):
        errors.append(f"missing expected finding_id {finding}")
    elif pin_allowed and issues:
        errors.append("positive control has issues")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--auditor", type=Path, default=LANE / "tools/mori-evidence-loss.py",
        help="L1-selected stdlib auditor; copied, never edited in place",
    )
    args = parser.parse_args()
    if Path(__file__).resolve().parent != SEAT.resolve():
        raise ValueError("probe must remain in its assigned MutCleanupDisposition directory")
    source = args.auditor.resolve(strict=True)
    if not source.is_relative_to(LANE.resolve()) or not source.is_file():
        raise ValueError("auditor must be a regular file within the mori lane")
    source_bytes = source.read_bytes()
    git_binary = shutil.which("git", path=os.defpath)
    if git_binary is None:
        raise ValueError("git is required for committed synthetic evidence")
    run = Path(tempfile.mkdtemp(prefix="probe-", dir=SEAT))
    root = run / "isolated-repo"
    root.mkdir()
    home = run / "home"
    home.mkdir()
    template = run / "empty-git-template"
    template.mkdir()
    environment = {
        "PATH": os.defpath,
        "HOME": str(home),
        "TMPDIR": str(LANE / ".scratch"),
        "LANG": "C.UTF-8",
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_CONFIG_SYSTEM": os.devnull,
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_TERMINAL_PROMPT": "0",
        "PYTHONDONTWRITEBYTECODE": "1",
    }

    def git(*arguments):
        command = [
            git_binary, "-C", str(root),
            "-c", "user.name=Synthetic Mutation Fixture",
            "-c", "user.email=mutation-fixture@invalid.local",
            "-c", "commit.gpgsign=false",
            "-c", f"core.hooksPath={template}",
            *arguments,
        ]
        completed = subprocess.run(
            command, env=environment, capture_output=True, timeout=TIMEOUT_SECONDS,
        )
        if completed.returncode:
            raise RuntimeError(
                f"isolated git setup failed: {command!r}; "
                f"rc={completed.returncode}; stderr={completed.stderr!r}"
            )
        return completed.stdout.decode("utf-8").strip()

    git("init", "--quiet", "--initial-branch=probe", f"--template={template}")
    auditor = run / "auditor.py"
    auditor.write_bytes(source_bytes)
    evidence = root / "evidence"
    evidence.mkdir()
    artifacts = {
        "baseline.md": b"SYNTHETIC required observation; not historical settlement evidence.\n",
        "deletion.md": b"SYNTHETIC observation disappeared; disposition remains unknown.\n",
        "cleanup.json": json_bytes({"id": WAVE, "wave_id": WAVE, "actor": CLEANUP_ACTOR}),
    }
    for name, actor in (
        ("disposition-independent.json", INDEPENDENT_ACTOR),
        ("disposition-same-actor.json", CLEANUP_ACTOR),
    ):
        artifacts[name] = json_bytes({
            "id": WAVE, "wave_id": WAVE, "actor": actor,
            "independent": True, "disposition": "cleanup-accounted",
        })
    for name, content in artifacts.items():
        (evidence / name).write_bytes(content)
    git("add", "--", "evidence")
    git("commit", "--quiet", "-m", "Synthetic committed evidence for one mutation probe")
    evidence_revision = git("rev-parse", "HEAD")

    def ref(name, **metadata):
        return {
            "path": f"evidence/{name}", "revision": evidence_revision,
            "sha256": sha256(artifacts[name]), **metadata,
        }

    row = {
        "id": WAVE, "state": "unresolved",
        "baseline": ref("baseline.md"), "deletion": ref("deletion.md"),
        "cleanup": ref("cleanup.json", actor=CLEANUP_ACTOR),
        "independent_disposition": None,
    }
    pristine = {"schema": "mori-loss-accounting-v1", "observations": [row]}
    required = root / "required.json"
    accounting = root / "accounting.json"
    required.write_bytes(json_bytes({
        "schema": "mori-required-observations-v1",
        "observations": [{
            "id": WAVE, "baseline": ref("baseline.md"),
            "evidence": "evidence/baseline.md:1",
        }],
    }))
    accounting.write_bytes(json_bytes(pristine))
    git("add", "--", "required.json", "accounting.json")
    git("commit", "--quiet", "-m", "Synthetic unresolved control inputs")
    fixture_revision = git("rev-parse", "HEAD")

    mutant = copy.deepcopy(pristine)
    mutant["observations"][0].update({
        "state": "disposed",
        "independent_disposition": ref(
            "disposition-same-actor.json", actor=CLEANUP_ACTOR,
            wave_id=WAVE, disposition="cleanup-accounted", independent=True,
        ),
    })
    independent = copy.deepcopy(mutant)
    independent["observations"][0]["independent_disposition"] = ref(
        "disposition-independent.json", actor=INDEPENDENT_ACTOR,
        wave_id=WAVE, disposition="cleanup-accounted", independent=True,
    )
    saved = {
        path: path.read_bytes()
        for path in [auditor, required, accounting, *(evidence / name for name in artifacts)]
    }
    command = [
        sys.executable, "-I", "-B", str(auditor), "audit", "--root", str(root),
        "--required", str(required), "--accounting", str(accounting),
    ]
    cases = {}

    def audit(label, content):
        accounting.write_bytes(content)
        stdout, stderr = b"", b""
        returncode, error = None, None
        try:
            completed = subprocess.run(
                command, cwd=root, env=environment, capture_output=True,
                timeout=TIMEOUT_SECONDS,
            )
            stdout, stderr = completed.stdout, completed.stderr
            returncode = completed.returncode
        except subprocess.TimeoutExpired as failure:
            stdout, stderr = failure.stdout or b"", failure.stderr or b""
            error = f"auditor exceeded {TIMEOUT_SECONDS}s"
        except OSError as failure:
            error = f"auditor launch failed: {failure}"
        (run / f"{label}.stdout").write_bytes(stdout)
        (run / f"{label}.stderr").write_bytes(stderr)
        try:
            data = json.loads(stdout)
        except (UnicodeError, ValueError):
            data = None
        drift = [
            str(path.relative_to(run)) for path, original in saved.items()
            if path != accounting and (not path.is_file() or path.read_bytes() != original)
        ]
        actual_accounting = accounting.read_bytes() if accounting.is_file() else None
        record = {
            "returncode": returncode, "error": error, "json": data,
            "stdout": stdout.decode("utf-8", errors="replace"),
            "stderr": stderr.decode("utf-8", errors="replace"),
            "stdout_sha256": sha256(stdout), "stderr_sha256": sha256(stderr),
            "accounting_sha256_before": sha256(content),
            "accounting_sha256_after": (
                sha256(actual_accounting) if actual_accounting is not None else None
            ),
            "other_input_drift": drift,
        }
        cases[label] = record
        return record

    interrupted = None
    try:
        audit("pristine", saved[accounting])
        audit("independent_control", json_bytes(independent))
        audit("mutated", json_bytes(mutant))
    except BaseException as failure:
        interrupted = f"{type(failure).__name__}: {failure}"
    finally:
        for path, original in saved.items():
            path.write_bytes(original)
        try:
            audit("restored", saved[accounting])
        except BaseException as failure:
            interrupted = f"restored detector failed: {type(failure).__name__}: {failure}"
        finally:
            for path, original in saved.items():
                path.write_bytes(original)

    hashes = {
        str(path.relative_to(run)): {
            "before": sha256(original), "after": sha256(path.read_bytes()),
            "restored_exact": path.read_bytes() == original,
        }
        for path, original in saved.items()
    }
    failures = []
    if interrupted:
        failures.append(interrupted)
    for label in ("pristine", "independent_control", "mutated", "restored"):
        if label not in cases:
            failures.append(f"{label}: detector did not run")
            continue
        record = cases[label]
        if record["error"] or record["other_input_drift"]:
            failures.append(f"{label}: timeout/launch failure or immutable input drift")
        if record["accounting_sha256_before"] != record["accounting_sha256_after"]:
            failures.append(f"{label}: detector changed its accounting input")
    blocked = {"omitted": 0, "retained": 1, "unresolved": 1, "disposed": 0, "invalid": 0}
    allowed = {"omitted": 0, "retained": 1, "unresolved": 1, "disposed": 1, "invalid": 0}
    for label, counts, pin_allowed, rc in (
        ("pristine", blocked, False, 1),
        ("independent_control", allowed, False, 1),
        ("restored", blocked, False, 1),
    ):
        if label in cases:
            failures.extend(f"{label}: {error}" for error in check(cases[label], counts, pin_allowed, rc))
    if any(not item["restored_exact"] for item in hashes.values()):
        failures.append("exact input-byte restoration failed")
    restored_behavior_matches = (
        "pristine" in cases and "restored" in cases
        and cases["pristine"]["returncode"] == cases["restored"]["returncode"]
        and cases["pristine"]["json"] == cases["restored"]["json"]
    )
    if not restored_behavior_matches:
        failures.append("restored detector behavior differs from pristine")
    mutant_errors = []
    verdict = "inconclusive"
    if not failures:
        observed = cases["mutated"]
        mutant_errors = check(
            observed, {"omitted": 0, "retained": 1, "disposed": 0, "invalid": 1},
            False, 1, FINDING,
        )
        if not mutant_errors:
            verdict = "killed"
        elif (
            observed["returncode"] == 0 and isinstance(observed["json"], dict)
            and observed["json"].get("pin_allowed") is True
        ):
            verdict = "survived"
    result = {
        "schema": "mori-round21-mutation-probe-v1", "verdict": verdict,
        "mutant": "unresolved -> disposed with independent:true but cleanup actor reused",
        "expected_finding_id": FINDING,
        "source": str(source), "source_sha256": sha256(source_bytes),
        "run_directory": str(run), "command": command,
        "evidence_revision": evidence_revision, "fixture_revision": fixture_revision,
        "cases": cases, "failures": failures, "mutant_detector_errors": mutant_errors,
        "restoration": hashes, "restored_behavior_matches": restored_behavior_matches,
        "synthetic_only": True,
    }
    result_path = run / "result.json"
    result_path.write_bytes(json_bytes(result))
    print(json.dumps({"verdict": verdict, "result": str(result_path)}, sort_keys=True))
    return {"killed": 0, "survived": 1, "inconclusive": 2}[verdict]


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as failure:
        print(json.dumps({
            "verdict": "inconclusive", "setup_error": f"{type(failure).__name__}: {failure}",
        }, sort_keys=True))
        raise SystemExit(2)
