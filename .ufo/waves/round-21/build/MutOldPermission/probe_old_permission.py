#!/usr/bin/env python3
"""Proposed round21 C2 mutation probe; author has not executed it.

L1 may run this file with --evaluator pointing to the stdlib classifier.
Only classify is invoked: two fixed six-case calls per phase, six calls total.
All generated bytes remain beneath this seat in a fresh probe-* directory.
Exit 0: exact expected kill; 1: survived; 2: inconclusive/setup/control failure.
"""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile


ROOT = Path("/home/vgpnk/Projects/shokunin/mori-shokunin")
SEAT = ROOT / ".ufo/waves/round-21/build/MutOldPermission"
TIMEOUT_SECONDS = 10


def encode(document):
    return (json.dumps(document, indent=2) + "\n").encode("utf-8")


def digest(data):
    return hashlib.sha256(data).hexdigest()


# Independent expectations transcribed from contract.md:20-25, not target output.
# Serialization reproduces frozen/cases.json, including its final newline.
FIELDS = (
    "id", "required_evidence_lost", "independent_disposition",
    "ordinary_state_change", "expected_class", "expected_pin_allowed",
)
ROWS = (
    ("loss-unknown", True, False, True, "census-regression", False),
    ("loss-cleanup-only", True, False, False, "census-regression", False),
    ("loss-independent-cleanup", True, True, False, "live-state", True),
    ("loss-independent-settlement", True, True, True, "live-state", True),
    ("ordinary-aging", False, False, True, "live-state", True),
    ("ordinary-state", False, False, False, "live-state", True),
)
FROZEN = encode({
    "schema": "mori-evidence-loss-cases-v1",
    "cases": [dict(zip(FIELDS, row)) for row in ROWS],
})
PRISTINE = encode({
    "schema": "mori-evidence-loss-rule-v1",
    "evidence_loss_blocks": True,
    "source": "round21 supersession of QUALITY67",
})
OLD_TOKEN = b'"evidence_loss_blocks": true'
NEW_TOKEN = b'"evidence_loss_blocks": false'
MUTANT = PRISTINE.replace(OLD_TOKEN, NEW_TOKEN, 1)

# Diagnostic witness, NOT a replacement frozen contract: inputs are identical;
# only the first two expected decision pairs become live-state / true.
# A full witness match proves all six observed decisions equal that vector,
# without depending on undocumented per-case JSON output field names.
permission_rows = json.loads(FROZEN)["cases"]
for row in permission_rows[:2]:
    row["expected_class"] = "live-state"
    row["expected_pin_allowed"] = True
WITNESS = encode({"schema": "mori-evidence-loss-cases-v1", "cases": permission_rows})

PINNED_RULE_SHA256 = "8bf6cd9f20fb1fefc25e7b3381deda0220dbe8fd5012b4a6baa9b37f0646bc95"
PINNED_CASES_SHA256 = "10603c9e2a506f0aab9e03036e76b9149621a875e762616acbbbfa9a52e66878"
BASELINE_SIGNATURE = ((0, 0), (1, 2))
MUTANT_SIGNATURE = ((1, 2), (0, 0))


def capture(command, run_dir, phase, label):
    """Preserve actual stdout/stderr/rc; setup failures never count as kills."""
    record = {"command": command, "timeout_seconds": TIMEOUT_SECONDS}
    try:
        process = subprocess.run(
            command, cwd=run_dir, input=b"", capture_output=True,
            timeout=TIMEOUT_SECONDS, check=False,
            env={
                "PATH": "/usr/bin:/bin", "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8",
                "TMPDIR": str(ROOT / ".scratch"),
            },
        )
        stdout, stderr = process.stdout, process.stderr
        record["returncode"] = process.returncode
    except subprocess.TimeoutExpired as exc:
        stdout, stderr = exc.stdout or b"", exc.stderr or b""
        record.update(returncode=None, error="detector timeout")
    except OSError as exc:
        stdout, stderr = b"", b""
        record.update(returncode=None, error=f"detector launch: {exc}")
    stdout_path = run_dir / f"{phase}.{label}.stdout"
    stderr_path = run_dir / f"{phase}.{label}.stderr"
    stdout_path.write_bytes(stdout)
    stderr_path.write_bytes(stderr)
    record.update(stdout=str(stdout_path), stderr=str(stderr_path))
    try:
        document = json.loads(stdout.decode("utf-8"))
        mismatched = document.get("mismatched") if isinstance(document, dict) else None
        if type(mismatched) is not int or not 0 <= mismatched <= len(ROWS):
            raise ValueError("expected integer mismatched in [0, 6]")
        if record["returncode"] != (0 if mismatched == 0 else 1):
            raise ValueError("rc disagrees with mismatch count or indicates setup failure")
        record["mismatched"] = mismatched
        record["output"] = document
    except (UnicodeDecodeError, ValueError) as exc:
        record.setdefault("error", f"detector output: {exc}")
    return record


def detector(run_dir, expected_files, phase):
    """Identical classifier commands, input paths and environment each phase."""
    def hashes():
        return {name: digest((run_dir / name).read_bytes()) for name in expected_files}

    expected_hashes = {name: digest(data) for name, data in expected_files.items()}
    before = hashes()
    commands = []
    for label, filename in (
        ("frozen", "frozen-cases.json"), ("witness", "permission-witness.json"),
    ):
        command = [
            sys.executable, "-I", "-B", str(run_dir / "evaluator.py"), "classify",
            "--rule", str(run_dir / "rule.json"),
            "--cases", str(run_dir / filename),
        ]
        commands.append(capture(command, run_dir, phase, label))
    after = hashes()
    return {
        "hashes_before": before, "hashes_after": after,
        "inputs_unchanged": before == expected_hashes == after,
        "calls": commands,
    }


def signature(result):
    if not result or not result["inputs_unchanged"]:
        return None
    if any("error" in call for call in result["calls"]):
        return None
    return tuple((call["returncode"], call["mismatched"]) for call in result["calls"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--evaluator", type=Path, default=ROOT / "tools/mori-evidence-loss.py",
        help="read-only source copied into this seat before any execution",
    )
    args = parser.parse_args()
    try:
        if Path(__file__).resolve().parent != SEAT or SEAT.resolve() != SEAT:
            raise ValueError("probe must stay in its assigned, non-symlink seat directory")
        if digest(PRISTINE) != PINNED_RULE_SHA256 or digest(FROZEN) != PINNED_CASES_SHA256:
            raise ValueError("embedded fixtures differ from the observed frozen bytes")
        if PRISTINE.count(OLD_TOKEN) != 1 or MUTANT == PRISTINE:
            raise ValueError("mutation must replace exactly one rule boolean token")
        original_rule = json.loads(PRISTINE)
        mutated_rule = json.loads(MUTANT)
        if original_rule.pop("evidence_loss_blocks") is not True:
            raise ValueError("pristine rule is not true")
        if mutated_rule.pop("evidence_loss_blocks") is not False or mutated_rule != original_rule:
            raise ValueError("mutation changed something besides the rule flag")
        evaluator_source = args.evaluator.resolve(strict=True)
        evaluator_bytes = evaluator_source.read_bytes()
        run_dir = Path(tempfile.mkdtemp(prefix="probe-", dir=SEAT))
        files = {
            "evaluator.py": evaluator_bytes, "rule.json": PRISTINE,
            "frozen-cases.json": FROZEN, "permission-witness.json": WITNESS,
        }
        for filename, contents in files.items():
            (run_dir / filename).write_bytes(contents)
    except (OSError, ValueError) as exc:
        print(json.dumps({"verdict": "inconclusive", "reason": f"setup: {exc}"}))
        return 2

    results, errors, restoration = {}, [], {}
    rule_path = run_dir / "rule.json"
    try:
        results["pristine"] = detector(run_dir, files, "pristine")
        rule_path.write_bytes(MUTANT)
        mutant_files = dict(files, **{"rule.json": MUTANT})
        results["mutated"] = detector(run_dir, mutant_files, "mutated")
    except (Exception, KeyboardInterrupt) as exc:
        errors.append(f"probe: {type(exc).__name__}: {exc}")
    finally:
        try:
            rule_path.write_bytes(PRISTINE)
            restoration["before_restored_detector_sha256"] = digest(rule_path.read_bytes())
            results["restored"] = detector(run_dir, files, "restored")
        except (Exception, KeyboardInterrupt) as exc:
            errors.append(f"restored detector: {type(exc).__name__}: {exc}")
        finally:
            # Restore again even if the restored detector failed or changed its input.
            try:
                rule_path.write_bytes(PRISTINE)
                final_bytes = rule_path.read_bytes()
                restoration.update(
                    final_sha256=digest(final_bytes), exact_bytes=final_bytes == PRISTINE,
                )
            except OSError as exc:
                restoration["exact_bytes"] = False
                errors.append(f"final restoration: {exc}")

    observed = {phase: signature(results.get(phase)) for phase in ("pristine", "mutated", "restored")}
    controls_ok = (
        not errors and restoration.get("exact_bytes") is True
        and observed["pristine"] == BASELINE_SIGNATURE
        and observed["restored"] == BASELINE_SIGNATURE
    )
    if not controls_ok:
        verdict, reason, rc = "inconclusive", "pristine/restored/integrity control failed", 2
    elif observed["mutated"] == MUTANT_SIGNATURE:
        verdict, reason, rc = "killed", "only the first two frozen decisions flip; mismatched=2", 0
    elif observed["mutated"] == BASELINE_SIGNATURE:
        verdict, reason, rc = "survived", "rule flag change left the six-case decision vector unchanged", 1
    else:
        verdict, reason, rc = "inconclusive", "mutant response does not establish the exact expected two-case flip", 2

    summary = {
        "schema": "mori-old-permission-mutation-probe-v1",
        "mutant": "isolated rule.json evidence_loss_blocks true -> false",
        "verdict": verdict, "reason": reason, "run_directory": str(run_dir),
        "evaluator_source": str(evaluator_source), "evaluator_sha256": digest(evaluator_bytes),
        "expected_changed_ids": [row[0] for row in ROWS[:2]],
        "expected_unchanged_ids": [row[0] for row in ROWS[2:]],
        "expected_signatures_frozen_then_witness": {
            "pristine": BASELINE_SIGNATURE, "mutated": MUTANT_SIGNATURE,
            "restored": BASELINE_SIGNATURE,
        },
        "observed_signatures_frozen_then_witness": observed,
        "first_two_only_confirmed": controls_ok and observed["mutated"] == MUTANT_SIGNATURE,
        "rule_sha256": {
            "pristine": digest(PRISTINE), "mutated_expected_bytes": digest(MUTANT),
            "restored_final": restoration.get("final_sha256"),
        },
        "frozen_cases_sha256": digest(FROZEN), "permission_witness_sha256": digest(WITNESS),
        "restoration": restoration, "errors": errors, "phases": results,
    }
    (run_dir / "result.json").write_bytes(encode(summary))
    print(json.dumps(summary, indent=2))
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
